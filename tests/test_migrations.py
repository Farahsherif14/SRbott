"""Tests for the Alembic migrations. Test database only (the "_test" guard).

- The round trip: down to an empty database, then up again. A downgrade that was never tested
  probably doesn't work, and we would find out during a failed deploy.
- `alembic check`: app/db/models.py and the migrations describe the same tables.
- The personal-data comments are in the database itself.
Skipped without a PostgreSQL DATABASE_URL.
"""

import asyncio

from alembic import command
from alembic.config import Config
from alembic.script import ScriptDirectory
from sqlalchemy import Row, text
from sqlalchemy.engine import URL

from app.db.models import PERSONAL_DATA, Base
from app.db.session import make_engine
from tests.conftest import require_test_database

APP_TABLES = {table.name for table in Base.metadata.sorted_tables}  # our 7 tables

TABLES_SQL = "SELECT table_name FROM information_schema.tables WHERE table_schema = 'public'"
VERSION_SQL = "SELECT version_num FROM alembic_version"
# Every column that has a comment, read from Postgres's own catalog (pg_catalog)
COMMENTS_SQL = """
    SELECT cls.relname, att.attname, col_description(att.attrelid, att.attnum)
    FROM pg_attribute att
    JOIN pg_class cls ON cls.oid = att.attrelid
    JOIN pg_namespace ns ON ns.oid = cls.relnamespace
    WHERE ns.nspname = 'public' AND att.attnum > 0 AND NOT att.attisdropped
      AND col_description(att.attrelid, att.attnum) IS NOT NULL
"""


def query(url: URL, sql: str) -> list[Row]:
    """Run one read-only query on the test database and return its rows."""

    async def run() -> list[Row]:
        engine = make_engine(require_test_database(url), pooled=False)
        try:
            async with engine.connect() as connection:
                return list(await connection.execute(text(sql)))
        finally:
            await engine.dispose()

    return asyncio.run(run())


def test_downgrade_to_empty_and_upgrade_again(alembic_config: Config, test_db_url: URL) -> None:
    head = ScriptDirectory.from_config(alembic_config).get_current_head()
    try:
        command.downgrade(alembic_config, "base")  # undo every migration

        assert {row[0] for row in query(test_db_url, TABLES_SQL)} == {"alembic_version"}
        assert query(test_db_url, VERSION_SQL) == []  # no version: an empty database
    finally:
        # Always back to head, even if an assert failed, so the other tests find their tables
        command.upgrade(alembic_config, "head")

    assert {row[0] for row in query(test_db_url, TABLES_SQL)} == APP_TABLES | {"alembic_version"}
    assert [row[0] for row in query(test_db_url, VERSION_SQL)] == [head]


def test_models_and_migrations_agree(alembic_config: Config) -> None:
    # Raises AutogenerateDiffsDetected if models.py has a change that no migration has.
    # Its limit: it doesn't compare CHECK rules (test_models.py tests every label instead)
    command.check(alembic_config)


def test_personal_data_columns_are_marked_in_the_database(test_db_url: URL) -> None:
    marked = {
        (table, column)
        for table, column, comment in query(test_db_url, COMMENTS_SQL)
        if comment == PERSONAL_DATA
    }
    assert marked == {
        ("users", "name"),
        ("users", "phone"),
        ("service_requests", "issue_description"),
        ("conversation_messages", "content"),
    }
